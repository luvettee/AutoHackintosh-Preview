#!/usr/bin/env python3
"""AutoHackintosh end-to-end orchestrator.

Runs the deterministic half of an installation: inventory, compatibility
assessment, dependency acquisition, EFI generation, validation and stick
preparation. It stops before anything destructive unless explicitly authorised.

Every stage is attributable and idempotent, and prints a machine-readable
summary that the agent can reason over. This script is deliberately boring: it
calls the small, individually-tested tools in this directory rather than
re-implementing them.

STAGES
------
    inventory    hardware + firmware + storage facts
    assess       compatibility verdict per component, recommended macOS
    deps         fetch and verify upstream dependencies
    recovery     download Apple's recovery image
    efi          generate a hardware-specific OpenCore EFI and validate it
    stick        (destructive, gated) write the USB
    report       assemble a redacted diagnostic report

USAGE
-----
    ./autohackintosh.py inventory
    ./autohackintosh.py assess --workdir ~/.cache/autohackintosh
    ./autohackintosh.py build  --workdir ~/.cache/autohackintosh
    ./autohackintosh.py stick  --workdir ... --device /dev/sdX --i-authorise-erase <SERIAL>
    ./autohackintosh.py report --workdir ...

Exit codes: 0 success, 1 failed/unverified, 2 needs a human decision, 3 usage.
"""

